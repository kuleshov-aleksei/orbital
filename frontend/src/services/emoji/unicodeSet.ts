function parseItem(item: string): UnicodeEmoji {
  const [main, extra = ""] = item.split("|")
  const spaceAt = main.indexOf(" ")
  const char = main.slice(0, spaceAt)
  const name = main.slice(spaceAt + 1)
  const keywords = `${name} ${extra}`.toLowerCase().split(/\s+/).filter(Boolean)
  return { kind: "unicode", ref: char, char, name, keywords }
}

const CATEGORIES: EmojiCategory[] = SOURCE.map(({ id, label, icon, items }) => ({
  id,
  label,
  icon,
  emojis: items.map(parseItem),
}))

const BY_REF = new Map(CATEGORIES.flatMap((c) => c.emojis.map((e) => [e.ref, e] as const)))

export const unicodeEmojiProvider: EmojiProvider = {
  id: "unicode",
  getCategories: () => CATEGORIES,
  resolve: (ref) => BY_REF.get(ref) ?? null,
}
